const menuToggle = document.querySelector(".menu-toggle");
const menu = document.querySelector("[data-menu]");
const year = document.querySelector("#year");
const languageButtons = document.querySelectorAll("[data-language]");

let activeLanguage = "ar";

const getStoredLanguage = () => {
  try {
    return window.localStorage.getItem("87code-language");
  } catch {
    return null;
  }
};

const storeLanguage = (language) => {
  try {
    window.localStorage.setItem("87code-language", language);
  } catch {
    // localStorage can be unavailable in private or restricted browsing modes.
  }
};

const setMenuState = (isOpen) => {
  if (!menuToggle || !menu) {
    return;
  }

  const dictionary = translations[activeLanguage];
  menu.classList.toggle("is-open", isOpen);
  menuToggle.setAttribute("aria-expanded", String(isOpen));
  menuToggle.setAttribute("aria-label", dictionary[isOpen ? "menu.close" : "menu.open"]);
  document.body.classList.toggle("menu-open", isOpen);
};

const applyLanguage = (language) => {
  const dictionary = translations[language] || translations.ar;
  activeLanguage = dictionary.lang;

  document.documentElement.lang = dictionary.lang;
  document.documentElement.dir = dictionary.dir;
  document.body.dataset.language = dictionary.lang;
  document.title = dictionary.metaTitle;

  const description = document.querySelector('meta[name="description"]');
  const ogTitle = document.querySelector('meta[property="og:title"]');
  const ogDescription = document.querySelector('meta[property="og:description"]');

  if (description) {
    description.setAttribute("content", dictionary.metaDescription);
  }

  if (ogTitle) {
    ogTitle.setAttribute("content", dictionary.metaTitle);
  }

  if (ogDescription) {
    ogDescription.setAttribute("content", dictionary.ogDescription);
  }

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    if (key && dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const key = element.getAttribute("data-i18n-aria-label");
    if (key && dictionary[key]) {
      element.setAttribute("aria-label", dictionary[key]);
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.getAttribute("data-i18n-alt");
    if (key && dictionary[key]) {
      element.setAttribute("alt", dictionary[key]);
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.getAttribute("data-language") === dictionary.lang;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  setMenuState(false);
};

if (year) {
  year.textContent = new Date().getFullYear();
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    const language = button.getAttribute("data-language") || "ar";
    applyLanguage(language);
    storeLanguage(language);
  });
});

if (menuToggle && menu) {
  menuToggle.addEventListener("click", () => {
    const isOpen = menuToggle.getAttribute("aria-expanded") === "true";
    setMenuState(!isOpen);
  });

  menu.addEventListener("click", (event) => {
    const link = event.target.closest("a");
    if (link) {
      setMenuState(false);
    }
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") {
      setMenuState(false);
    }
  });
}

applyLanguage(getStoredLanguage() || "ar");

const revealItems = document.querySelectorAll(".reveal");

if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.16 }
  );

  revealItems.forEach((item) => observer.observe(item));
} else {
  revealItems.forEach((item) => item.classList.add("is-visible"));
}
